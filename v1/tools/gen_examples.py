"""Generate v1/docs/worked-examples.md from the committed study files.

The sentences come from render.py and the derivation and data tables from
resolve.py, so the document shows what the reference tools actually produce.

  python v1/tools/gen_examples.py
"""
from __future__ import annotations

import json

from common import STUDIES, V1, read_json
from render import Renderer
from resolve import data_requirements, derivation_order

TITLES = {
    "cdiscpilot01": (
        "CDISC Pilot (CDISCPILOT01)",
        "Xanomeline in mild to moderate Alzheimer's disease. Four analyses of change from baseline, all instances "
        "of one template, `T.CFB_ANCOVA`. The study has no source document, so document anchoring does not apply.",
        ["AC.PRIMARY.ADASCOG", "AC.SENS.ADASCOG.TP"],
    ),
    "pre0102": (
        "PrE0102",
        "Fulvestrant plus everolimus in metastatic breast cancer. Four descriptive time-to-event analyses, all "
        "instances of `T.PFS_KaplanMeier`, each anchored to quoted passages of the study's statistical analysis plan.",
        ["AC.PRIMARY.PFS", "AC.SENS.PFS.ITT"],
    ),
}


def block(lines):
    return ["```", *lines, "```", ""]


def main():
    out = [
        "# Worked examples", "",
        "Two studies are carried through every layer. Both come from the SmartPhrase proof of concept on",
        "`estimands_01`; here they are expressed in the candidate v1 model and checked by its validator.",
        "The sentences and tables below are produced by the reference tools from the committed files",
        "(`v1/tools/render.py`, `v1/tools/resolve.py`), and regenerated by `v1/tools/gen_examples.py`.", "",
        "Identifiers marked `illustrative` in the study files (USDM, ARS and Biomedical Concept identifiers) are",
        "plausible stand-ins, not registered identifiers.", "",
    ]
    for s, (title, intro, traced) in TITLES.items():
        d = read_json(STUDIES / s / "analysis_set.json")
        r = Renderer(d)
        out += [f"## {title}", "", intro, "", f"File: `v1/studies/{s}/analysis_set.json`", "",
                "### Analysis Concepts", "",
                "| Analysis Concept | Template | Addresses estimand | Role | Intercurrent events handled |",
                "| --- | --- | --- | --- | --- |"]
        for a in d["analyses"]:
            handled = "; ".join(
                f"{x['intercurrentEvent']}: {x['strategy']}" + (" (study default)" if x["basis"] == "studyDefault" else "")
                for x in a.get("iceHandlings", [])) or "none in scope"
            out.append(f"| `{a['id']}` | `{a['template']}` | `{a.get('addressesEstimand')}` | "
                       f"{a.get('analysisRole')} | {handled} |")
        out += ["", "### Model to text", "",
                "The sentence each Analysis Concept generates, in the three languages that have a language pack.", ""]
        first = d["analyses"][0]
        for lang in ("en", "fr", "de"):
            out += [f"**{first['id']}** ({lang})", "", f"> {r.sentence(first, lang)}", ""]
        out += ["The other analyses, in English:", ""]
        out += [f"- `{a['id']}`: {r.sentence(a, 'en')}" for a in d["analyses"][1:]]
        out += ["", "### Analysis to derivation, and specification to data", ""]
        for aid in traced:
            order = derivation_order(d, aid)
            lines = [aid, "  derivations, in order: " +
                     (" -> ".join(order) if order else "(none in the library for time-to-event data)")]
            for q in data_requirements(d, aid):
                target = ".".join(x for x in (q["dataset"], q["variable"]) if x) or "(unbound)"
                lines.append(f"  {q['input']:13} {q['concept']:16} <- {target}"
                             + (f" WHERE {q['where']}" if q["where"] else "")
                             + (f"   [{q['note']}]" if q["note"] else ""))
            out += block(lines)
        if s == "cdiscpilot01":
            out += [
                "The primary analysis handles treatment discontinuation with the hypothetical strategy, implemented by",
                "`T.LOCF_Imputation`, so its change from baseline is taken from LOCF-imputed data. The sensitivity analysis",
                "handles the same event with the treatment-policy strategy and reads the data as observed. That is a",
                "different estimand (`EST.SENS.TP`), and a different derivation chain.", ""]
        else:
            out += [
                "`AVAL` carries time to event only where `PARAMCD` is `PFS`. The library's class-level binding marks",
                "`AVAL` as parameter-dependent, and the study's value-level binding resolves it. The same template serves",
                "progression-free survival, overall survival and time to progression; only the event changes.", "",
                "### Anchored to the source document", "",
                "Every use of a phrase is tied to the passage of the plan that licenses it. For example, in "
                "`AC.PRIMARY.PFS`:", ""]
            for pi in first["phrases"]:
                for ref in pi.get("sapRefs", [])[:1]:
                    out.append(f"- `{pi['phrase']}` — section {ref['section']}: \"{ref['quote']}\"")
            out.append("")
        ext = read_json(STUDIES / s / "esap-extension.example.json")
        out += ["### What an eSAP model would add", "",
                f"`v1/studies/{s}/esap-extension.example.json` is a non-normative example of the extension point",
                "(decision D13). It groups the analyses into a reporting event and records how each intercurrent event is",
                "detected, referring to the Analysis Concepts and study concepts above by identifier:", ""]
        if ext["iceAscertainments"]:
            out += block([json.dumps(ext["iceAscertainments"][0], indent=2, ensure_ascii=False)])
    (V1 / "docs" / "worked-examples.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote docs/worked-examples.md")


if __name__ == "__main__":
    main()
